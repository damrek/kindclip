export function isLocale(value: string): value is Locale {
  return (LOCALES as string[]).includes(value);
}

/** Stored choice or default (es). Pass the raw localStorage value (or null). */
export function loadLocale(stored: string | null): Locale {
  return stored !== null && isLocale(stored) ? stored : "es";
}

/** Resolve a key with optional {param} interpolation; falls back to the key. */
export function translate(locale: Locale, key: I18nKey, params?: TranslateParams): string {
  const template: string = DICTIONARIES[locale]?.[key] ?? key;
  if (!params) {
    return template;
  }
  return Object.entries(params).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

/** Context key + shape shared between App (provider) and components. */
export const I18N_CONTEXT_KEY = "kindclip-i18n";

export interface I18nContext {
  readonly locale: Locale;
  t: (key: I18nKey, params?: TranslateParams) => string;
  setLocale: (locale: Locale) => void;
}
